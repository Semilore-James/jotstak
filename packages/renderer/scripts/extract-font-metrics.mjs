// Reads the shipped font files and writes src/font-metrics.ts.
//
// ADR-002 requires the baseline offset to be DERIVED from font metrics rather
// than eyeballed, because "text sits on the rule" is a geometric promise and a
// guess is wrong by a fraction of a pixel that compounds into visible drift.
// The first hand-written attempt had Lora's descent as 0.302; it is 0.274.
//
// Run: npm run metrics -w @jotstak/renderer
// A test asserts the committed values still match the font files, so a Fontsource
// bump that changes metrics fails CI instead of silently shifting every baseline.

import * as fontkit from "fontkit";
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));

/** Families whose metrics the layout depends on, and the file to measure. */
const TARGETS = [
  { key: "lora", family: "Lora", file: "@fontsource/lora/files/lora-latin-400-normal.woff2" },
  { key: "caveat", family: "Caveat", file: "@fontsource/caveat/files/caveat-latin-600-normal.woff2" },
];

export function measure(file) {
  const font = fontkit.openSync(require.resolve(file));
  const upm = font.unitsPerEm;
  const lower = "abcdefghijklmnopqrstuvwxyz";
  const widths = [...lower].map((c) => font.layout(c).advanceWidth);
  return {
    unitsPerEm: upm,
    ascent: +(font.ascent / upm).toFixed(4),
    descent: +(Math.abs(font.descent) / upm).toFixed(4),
    lineGap: +(font.lineGap / upm).toFixed(4),
    meanLowercaseAdvance: +(widths.reduce((a, b) => a + b, 0) / widths.length / upm).toFixed(4),
  };
}

const metrics = Object.fromEntries(TARGETS.map((t) => [t.key, { family: t.family, ...measure(t.file) }]));

// ── Advance widths (ARC-15) ──────────────────────────────────────────────
// The renderer has to know how wide a diagram will be BEFORE a browser lays it
// out, to decide whether it fits the column, needs the full page, or needs a
// landscape page of its own. So it measures text itself, from the same font
// files the browser will use. Per-character advances in font units; kerning is
// deliberately ignored and covered by a safety margin measured in the tests.
const ADVANCE_TARGETS = [
  { key: "lora-400", file: "@fontsource/lora/files/lora-latin-400-normal.woff2" },
  { key: "lora-600", file: "@fontsource/lora/files/lora-latin-600-normal.woff2" },
];
const CHARSET = [
  ...Array.from({ length: 95 }, (_, i) => String.fromCodePoint(32 + i)), // printable ASCII
  ...Array.from({ length: 96 }, (_, i) => String.fromCodePoint(160 + i)), // Latin-1 supplement
  ..."‘’“”–—…•·€→←↑↓×÷™©®°",
];

export function advances(file) {
  const font = fontkit.openSync(require.resolve(file));
  const widths = {};
  for (const ch of CHARSET) {
    const glyph = font.glyphForCodePoint(ch.codePointAt(0));
    if (!glyph || glyph.id === 0) continue; // not in the subset: see fallback
    widths[ch] = glyph.advanceWidth;
  }
  // A character the font lacks is drawn by a FALLBACK font, whose width we
  // cannot know — so assume a full em. Measured, not guessed: an average
  // lowercase letter under-estimated "1,240 → 2,000" by 6.8%, because the
  // browser drew the arrow from another face at exactly 1em.
  return { unitsPerEm: font.unitsPerEm, fallback: font.unitsPerEm, widths };
}

const fontAdvances = Object.fromEntries(ADVANCE_TARGETS.map((t) => [t.key, advances(t.file)]));

const body = `// GENERATED by scripts/extract-font-metrics.mjs — do not edit by hand.
// Run \`npm run metrics -w @jotstak/renderer\` to regenerate after a font bump.
//
// Measured from the woff2 files actually shipped, because the baseline offset
// that puts text ON the ruled line is computed from these numbers (ADR-002).

export interface FontMetrics {
  family: string;
  unitsPerEm: number;
  /** Ascent above the baseline, in em. */
  ascent: number;
  /** Descent below the baseline, in em (positive). */
  descent: number;
  lineGap: number;
  /** Mean advance width of a–z, in em. Used to size metric-matched fallbacks. */
  meanLowercaseAdvance: number;
}

export const FONT_METRICS = ${JSON.stringify(metrics, null, 2)} as const satisfies Record<string, FontMetrics>;

export interface FontAdvances {
  unitsPerEm: number;
  /** Advance used for any character not in \`widths\`, in font units. */
  fallback: number;
  /** Advance width per character, in font units. Kerning is not included. */
  widths: Readonly<Record<string, number>>;
}

/** Per-character advance widths, so the renderer can size diagrams before layout (ARC-15). */
export const FONT_ADVANCES: Readonly<Record<"lora-400" | "lora-600", FontAdvances>> = ${JSON.stringify(fontAdvances)};
`;

writeFileSync(join(here, "..", "src", "font-metrics.ts"), body);
console.log("wrote src/font-metrics.ts");
for (const [k, m] of Object.entries(metrics)) {
  console.log(`  ${k}: ascent ${m.ascent} descent ${m.descent} gap ${m.lineGap} advance ${m.meanLowercaseAdvance}`);
}
