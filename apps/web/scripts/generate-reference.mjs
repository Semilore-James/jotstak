// Generates the primitive reference from the schema and the renderer's own
// function map, so the docs cannot drift from the tool.
//
// The page is organised by FUNCTION rather than alphabetically, because the
// honest answer to "how much is there to learn?" is the number of functions,
// not the number of names. Several names are presets over one function.

import { PRIMITIVES, UNIVERSAL_PARAMS, getPrimitive } from "@jotstak/schema";
import { RENDER_FUNCTIONS } from "@jotstak/renderer";
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "src", "content", "docs", "docs", "reference.mdx");

const FUNCTION_NOTES = {
  panel: "A bounded region that clears the ruling and holds anything — fields, prose, or other blocks. `@panel` is the function; the rest are presets that set its label, badge and accent for you. Use `@panel` directly when the PM vocabulary does not fit, or when a document should not read as jargon.",
  columns: "Places regions side by side. Each `key:` in the body becomes a column.",
  quote: "Someone else's words, with as much or as little provenance as you have. A pull quote and a research citation are the same thing.",
  chips: "A compact row of document metadata.",
  margin: "An annotation in the margin channel, beside the block it follows.",
  heading: "Section titles. `@cover` is the full-width variant that introduces a major section.",
  list: "Bullets and numbered lists, nested by indentation.",
  divider: "A horizontal break between sections.",
  table: "Rows and columns, without pipes.",
  tree: "A hierarchy defined by indentation.",
  matrix: "A 2×2 with named axes.",
  timeline: "Events along an axis.",
  journey: "Stages left to right, optionally in parallel lanes.",
  star: "A central entity with satellites around it.",
  sticky: "Clustered notes, for synthesis.",
  freeform: "The escape hatch, for what the named functions cannot express.",
  inline: "Marks that sit inside a line rather than forming a block.",
  config: "Configures the document. Renders nothing itself.",
};

const esc = (s) => String(s).replace(/\|/g, "\\|").replace(/</g, "&lt;");

function paramTable(spec) {
  const own = spec.params;
  if (own.length === 0) return "_No parameters of its own._\n";
  const rows = own.map((p) => {
    const type = p.type === "enum" ? (p.enumValues ?? []).map((v) => `\`${v}\``).join(" · ") : `\`${p.type}\``;
    return `| \`${p.name}\` | ${type} | ${p.required ? "**yes**" : "no"} | ${p.default ? `\`${p.default}\`` : "—"} | ${esc(p.description)} |`;
  });
  return ["| Param | Type | Required | Default | Meaning |", "| --- | --- | --- | --- | --- |", ...rows].join("\n") + "\n";
}

const fnCount = Object.keys(RENDER_FUNCTIONS).length;
const nameCount = PRIMITIVES.length;

let md = `---
title: Reference
description: Every primitive in Jotstak, grouped by what it actually does.
---

{/* GENERATED by apps/web/scripts/generate-reference.mjs — do not edit by hand. */}

Jotstak has **${fnCount} rendering functions** across **${nameCount} names**. Several names are
presets over the same function: \`@risk\` and \`@decision\` are both a panel, and
produce identical markup with different defaults. Learn the functions; the
presets are optional shorthand.

Everything here is optional. \`.jot\` is a superset of Markdown, so a file using
none of it still renders.

## Parameters every primitive accepts

${paramTable({ params: UNIVERSAL_PARAMS })}
## Writing parameters

Parameters go after the shortcode, or in a parenthesised list that may span
lines when there are enough of them to hurt readability. Both forms mean the
same thing.

\`\`\`jot
@decision title="Use Astro" status=accepted

@decision(
  title="Use Astro"
  status=accepted
  date=2026-09-19
)
\`\`\`

## Nesting

Indent a block inside another block's body and it becomes a child of it. This
is why the primitive set is small: two ideas that need to appear together do
not need a third primitive.

\`\`\`jot
@decision(title="Move to usage-based pricing" status=accepted)
  context: Seat pricing punishes the teams who adopt fastest

  @metric(name="Weekly active teams" value="1,240" trend=up)
    Growing 8% week-over-week.
\`\`\`

`;

for (const [fn, names] of Object.entries(RENDER_FUNCTIONS)) {
  const specs = names.map(getPrimitive).filter(Boolean);
  if (specs.length === 0) continue;

  md += `---\n\n## ${fn}\n\n${FUNCTION_NOTES[fn] ?? ""}\n\n`;
  md += names.length > 1
    ? `Written as: ${names.map((n) => `\`@${n}\``).join(", ")} — all one function.\n\n`
    : "";

  for (const spec of specs) {
    md += `### \`@${spec.name}\`\n\n`;
    if (spec.aliases?.length) md += `Also: ${spec.aliases.map((a) => `\`@${a}\``).join(", ")}\n\n`;
    md += `${spec.summary}\n\n`;
    md += `Body: \`${spec.bodyShape}\`${spec.breaksRuling ? " · clears the ruled lines" : ""}\n\n`;
    md += paramTable(spec) + "\n";
    if (spec.examples.length > 0) {
      md += "```jot\n" + spec.examples.join("\n\n") + "\n```\n\n";
    }
  }
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, md);
console.log(`wrote reference.mdx — ${fnCount} functions, ${nameCount} primitives`);
